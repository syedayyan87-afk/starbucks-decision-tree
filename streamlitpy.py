import streamlit as st
import pandas as pd
import joblib
from pathlib import Path

st.set_page_config(
    page_title="Starbucks Decision Tree",
    page_icon="☕",
    layout="wide"
)

st.title("☕ From Beans to Bytes")
st.subheader("Starbucks Beverage Category Prediction")

st.write(
    "Upload your Starbucks dataset to predict beverage "
    "categories using a trained Decision Tree."
)

MODEL_PATH = Path(__file__).parent / "starbucks_decision_tree.pkl"


@st.cache_resource
def load_model():
    return joblib.load(MODEL_PATH)


if not MODEL_PATH.exists():
    st.error(
        "Model file not found. Upload "
        "starbucks_decision_tree.pkl to the B2B folder."
    )
    st.stop()

try:
    model = load_model()
except Exception as e:
    st.error(f"Could not load model: {e}")
    st.stop()

st.success("Trained model loaded successfully!")

uploaded_file = st.file_uploader(
    "Upload Starbucks CSV file",
    type=["csv"]
)

if uploaded_file is not None:
    try:
        uploaded_df = pd.read_csv(uploaded_file)

        st.write("### Dataset Preview")
        st.dataframe(uploaded_df.head())

        preprocessor = model.named_steps["preprocessor"]
        expected_columns = list(
            preprocessor.feature_names_in_
        )

        missing_columns = [
            col for col in expected_columns
            if col not in uploaded_df.columns
        ]

        if missing_columns:
            st.error(
                "Required columns are missing: "
                + ", ".join(missing_columns)
            )
        else:
            X = uploaded_df[expected_columns].copy()

            for col in X.select_dtypes(
                include=["bool"]
            ).columns:
                X[col] = X[col].astype(str)

            if st.button("Predict Categories"):
                predictions = model.predict(X)

                results = uploaded_df.copy()
                results["predicted_category"] = predictions

                st.write("### Prediction Results")
                st.dataframe(results)

                st.download_button(
                    label="Download Predictions CSV",
                    data=results.to_csv(
                        index=False
                    ).encode("utf-8"),
                    file_name="starbucks_predictions.csv",
                    mime="text/csv"
                )

    except Exception as e:
        st.error(f"Could not process CSV: {e}")